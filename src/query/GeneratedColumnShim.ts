/**
 * GeneratedColumnShim — PostgreSQL GENERATED column compatibility shim for SQLite.
 *
 * SQLite supports generated columns but uses a different syntax than
 * PostgreSQL. This shim detects and rewrites PG's generated column
 * syntax into SQLite-compatible form.
 *
 * ## Syntax Mapping
 *
 * | PG Syntax                                    | SQLite Syntax              |
 * |:---------------------------------------------|:---------------------------|
 * | `col TYPE GENERATED ALWAYS AS (e) STORED`    | `col TYPE AS (e) STORED`   |
 * | `col TYPE GENERATED ALWAYS AS (e)`           | `col TYPE AS (e)`          |
 * | `col TYPE GENERATED ALWAYS AS IDENTITY`      | `col TYPE` (+ seq + guard) |
 * | `col TYPE GENERATED BY DEFAULT AS IDENTITY`  | `col TYPE` (+ seq)         |
 *
 * ## Real Logic (G11)
 * - Store generated column definitions in `__generated_columns` system table
 * - resolveDependencies(sql, defs) — detect columns referenced in expressions
 * - computeGeneratedValues(row, tableColumns, genCols) — compute generated values at INSERT/UPDATE time
 *
 * @module GeneratedColumnShim
 */

import { PinoLogger } from '../monitoring/PinoLogger';

const logger = PinoLogger.forComponent('GeneratedColumnShim');

// ── Types ────────────────────────────────────────────────────────

export interface IdentityColumnInfo {
  /** Column name */
  table: string;
  /** Column name */
  col: string;
  /** 'always' for GENERATED ALWAYS, 'default' for GENERATED BY DEFAULT */
  type: 'always' | 'default';
  /** Auto-generated sequence name (table_col_seq) */
  seqName: string;
}

export interface GeneratedColumnResult {
  /** Rewritten SQL (unchanged if no generated column syntax found) */
  sql: string;
  /** Whether a generated column pattern was detected and rewritten */
  rewritten: boolean;
  /** Identity column metadata (only populated for IDENTITY columns) */
  identityCols?: IdentityColumnInfo[];
}

export interface GeneratedColumnDef {
  /** Column name */
  name: string;
  /** The expression used to generate the column (e.g., "a + b") */
  expression: string;
  /** Whether it's STORED (SQLite only supports STORED) */
  stored: boolean;
  /** The list of column names this expression depends on */
  dependencies: string[];
}

// ── Constants — Regex Patterns ──────────────────────────────────

const GENERATED_ALWAYS_AS_RE = /GENERATED\s+ALWAYS\s+AS\s*/i;

/** Matches GENERATED ALWAYS AS IDENTITY (with optional sequence options) */
const GENERATED_ALWAYS_IDENTITY_RE = /\s+GENERATED\s+ALWAYS\s+AS\s+IDENTITY\s*(?:\([^)]*\))?\s*/i;

/** Matches GENERATED BY DEFAULT AS IDENTITY (with optional sequence options) */
const GENERATED_BY_DEFAULT_IDENTITY_RE = /\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s*(?:\([^)]*\))?\s*/i;

export const GENERATED_IDENTITY_RE = /\s+GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY\s*(?:\([^)]*\))?\s*/i;

const GENERATED_COLUMN_DETECT_RE = /GENERATED\s+(?:ALWAYS\s+AS|BY\s+DEFAULT\s+AS\s+IDENTITY)/i;

/**
 * Regex to extract (tableName, columnName, type, typeModifier) from a column definition
 * in a CREATE TABLE. Handles patterns like:
 *   id INT GENERATED ALWAYS AS IDENTITY
 *   id INTEGER GENERATED BY DEFAULT AS IDENTITY
 */
const IDENTIFY_COLUMN_DEF_RE = /(\w+)\s+(\w+(?:\s*\([^)]*\))?)\s+GENERATED\s+(ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY/i;

// ── Public API ───────────────────────────────────────────────────

export function detectGeneratedColumn(sql: string): boolean {
  if (typeof sql !== 'string' || sql.trim().length === 0) return false;
  return GENERATED_COLUMN_DETECT_RE.test(sql);
}

/**
 * Rewrite generated column syntax from PG to SQLite, and collect identity column metadata.
 *
 * For GENERATED ALWAYS AS (expr) / AS (expr) STORED:
 *   → `col TYPE AS (expr) [STORED]`
 *
 * For GENERATED {ALWAYS|BY DEFAULT} AS IDENTITY:
 *   → `col TYPE` (strip IDENTITY, keep the type)
 *   → Returns identityCols with table/col/type/seqName
 *
 * @param sql         The SQL to rewrite (CREATE TABLE DDL)
 * @param tableName   Optional table name to use for identity sequence naming.
 *                    If not provided, it's extracted from the CREATE TABLE statement.
 * @returns Rewritten SQL with identity column metadata
 */
export function rewriteGeneratedColumn(
  sql: string,
  tableName?: string,
): GeneratedColumnResult {
  if (typeof sql !== 'string' || sql.trim().length === 0) {
    return { sql: '', rewritten: false };
  }

  const trimmed = sql.trim();
  let rewritten = trimmed;
  const identityCols: IdentityColumnInfo[] = [];

  // Determine the table name from the SQL if not provided
  if (!tableName) {
    const tableMatch = rewritten.match(/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\S+)/i);
    if (tableMatch) {
      tableName = tableMatch[1].replace(/["`]/g, '');
    }
  }

  // Phase 1: Handle GENERATED ALWAYS AS IDENTITY (must come before Phase 2 to avoid
  // "GENERATED ALWAYS AS " consuming the IDENTITY keyword)
  if (GENERATED_ALWAYS_IDENTITY_RE.test(rewritten) && tableName) {
    // Extract all identity column definitions
    const identityMatches = rewritten.matchAll(
      /(\w+)\s+(\w+(?:\s*\([^)]*\))?)\s+GENERATED\s+ALWAYS\s+AS\s+IDENTITY\s*(?:\([^)]*\))?/gi,
    );
    for (const match of identityMatches) {
      const colName = match[1];
      const seqName = `${tableName}_${colName}_seq`.toLowerCase();
      identityCols.push({
        table: tableName.toLowerCase(),
        col: colName.toLowerCase(),
        type: 'always',
        seqName,
      });
    }

    // Strip GENERATED ALWAYS AS IDENTITY (including optional options)
    rewritten = rewritten.replace(GENERATED_ALWAYS_IDENTITY_RE, ' ');
  }

  // Phase 2: Handle GENERATED ALWAYS AS (expr) [STORED]
  if (GENERATED_ALWAYS_AS_RE.test(rewritten)) {
    rewritten = rewritten.replace(GENERATED_ALWAYS_AS_RE, 'AS ');
  }

  // Phase 3: Handle GENERATED BY DEFAULT AS IDENTITY
  if (GENERATED_BY_DEFAULT_IDENTITY_RE.test(rewritten) && tableName) {
    // Extract all identity column definitions
    const identityMatches = rewritten.matchAll(
      /(\w+)\s+(\w+(?:\s*\([^)]*\))?)\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s*(?:\([^)]*\))?/gi,
    );
    for (const match of identityMatches) {
      const colName = match[1];
      const seqName = `${tableName}_${colName}_seq`.toLowerCase();
      identityCols.push({
        table: tableName.toLowerCase(),
        col: colName.toLowerCase(),
        type: 'default',
        seqName,
      });
    }

    // Strip GENERATED BY DEFAULT AS IDENTITY (keeping the column type)
    rewritten = rewritten.replace(GENERATED_BY_DEFAULT_IDENTITY_RE, ' ');
  }

  // Clean up any double spaces from stripping
  rewritten = rewritten.replace(/\s{2,}/g, ' ').trim();

  const hasChanged = rewritten !== trimmed || identityCols.length > 0;
  if (hasChanged) {
    logger.debug(
      { before: trimmed, after: rewritten, identityCols: identityCols.length },
      'Generated column syntax rewritten',
    );
  }
  return {
    sql: rewritten,
    rewritten: hasChanged,
    identityCols: identityCols.length > 0 ? identityCols : undefined,
  };
}

/**
 * Extract generated column definitions from a CREATE TABLE SQL.
 * After rewriting, parse the AS (expr) STORED clauses to extract metadata.
 *
 * @param sql - The rewritten SQL (after rewriteGeneratedColumn)
 * @returns Array of generated column definitions
 */
export function extractGeneratedDefs(sql: string): GeneratedColumnDef[] {
  if (!sql || typeof sql !== 'string') return [];

  const defs: GeneratedColumnDef[] = [];

  // Match column definitions containing AS (expr) [STORED]
  // Pattern: column_name TYPE AS (expr) [STORED]
  const genColRe = /(\w+)\s+\w+(?:\([^)]*\))?\s+AS\s*\(([^)]+)\)\s*(STORED)?/gi;
  let match: RegExpExecArray | null;

  while ((match = genColRe.exec(sql)) !== null) {
    const name = match[1];
    const expression = match[2].trim();
    const stored = !!match[3];

    const dependencies = resolveDependencies(expression, []);

    defs.push({ name, expression, stored, dependencies });
  }

  return defs;
}

/**
 * Resolve column dependencies from a generated column expression.
 * Parses the expression and extracts referenced column names.
 *
 * @param expression - The generation expression (e.g., "a + b", "upper(name)")
 * @param knownColumns - Optional list of known columns for validation
 * @returns Array of column names referenced in the expression
 */
export function resolveDependencies(expression: string, knownColumns: string[]): string[] {
  if (!expression || typeof expression !== 'string') return [];

  const deps: string[] = [];

  // Match identifier-like tokens: letters/numbers/underscores, not SQL keywords
  const tokens = expression.match(/\b([a-zA-Z_][a-zA-Z0-9_]*)\b/g) || [];
  const sqlKeywords = new Set([
    'AND', 'OR', 'NOT', 'IN', 'IS', 'NULL', 'TRUE', 'FALSE',
    'AS', 'ON', 'TO', 'BY', 'FOR', 'IF', 'THEN', 'ELSE', 'END',
    'CASE', 'WHEN', 'THEN', 'ELSE', 'END', 'LIKE', 'BETWEEN',
    'EXISTS', 'ALL', 'ANY', 'SOME', 'DISTINCT', 'ASC', 'DESC',
    'ABS', 'COALESCE', 'NULLIF', 'UPPER', 'LOWER', 'LENGTH',
    'TRIM', 'SUBSTR', 'SUBSTRING', 'CHAR_LENGTH', 'CHARACTER_LENGTH',
    'MOD', 'POWER', 'SQRT', 'ROUND', 'CEIL', 'FLOOR', 'GREATEST', 'LEAST',
  ]);

  for (const token of tokens) {
    const upper = token.toUpperCase();
    if (!sqlKeywords.has(upper)) {
      // Check if it looks like a column reference (not a number)
      if (!/^\d+$/.test(token)) {
        if (!deps.includes(token)) {
          deps.push(token);
        }
      }
    }
  }

  return deps;
}

/**
 * Compute generated column values for a row being inserted or updated.
 *
 * @param row - The row data as a Map or object of column name -> value
 * @param tableColumns - All column names in the table (in order)
 * @param genCols - Generated column definitions
 * @returns A Map of generated column name -> computed value
 */
export function computeGeneratedValues(
  row: Record<string, any>,
  tableColumns: string[],
  genCols: GeneratedColumnDef[],
): Record<string, any> {
  const computed: Record<string, any> = {};

  for (const genCol of genCols) {
    try {
      const value = evaluateExpression(genCol.expression, row);
      computed[genCol.name] = value;
    } catch (err: any) {
      logger.error(
        { column: genCol.name, expression: genCol.expression, error: err.message },
        'Failed to compute generated column value',
      );
      computed[genCol.name] = null;
    }
  }

  return computed;
}

/**
 * Simple expression evaluator for generated column expressions.
 * Supports: arithmetic, string functions, COALESCE, NULLIF, CASE.
 *
 * @param expression - The expression to evaluate
 * @param row - The row data
 * @returns The computed value
 */
function evaluateExpression(expression: string, row: Record<string, any>): any {
  const trimmed = expression.trim();

  // Handle NULL literal
  if (/^\s*NULL\s*$/i.test(trimmed)) return null;

  // Handle boolean literals
  if (/^\s*TRUE\s*$/i.test(trimmed)) return 1;
  if (/^\s*FALSE\s*$/i.test(trimmed)) return 0;

  // Handle numeric literals
  if (/^\s*-?\d+(?:\.\d+)?\s*$/.test(trimmed)) {
    const num = Number(trimmed);
    return isNaN(num) ? null : num;
  }

  // Handle string literals
  const strMatch = trimmed.match(/^\s*'([^']*)'\s*$/);
  if (strMatch) return strMatch[1];

  // Handle COALESCE
  const coalesceMatch = trimmed.match(/^\s*COALESCE\s*\(\s*(.+)\s*\)\s*$/i);
  if (coalesceMatch) {
    const args = splitArgs(coalesceMatch[1]);
    for (const arg of args) {
      const val = evaluateExpression(arg.trim(), row);
      if (val !== null && val !== undefined) return val;
    }
    return null;
  }

  // Handle NULLIF
  const nullifMatch = trimmed.match(/^\s*NULLIF\s*\(\s*(.+)\s*\)\s*$/i);
  if (nullifMatch) {
    const args = splitArgs(nullifMatch[1]);
    if (args.length === 2) {
      const v1 = evaluateExpression(args[0].trim(), row);
      const v2 = evaluateExpression(args[1].trim(), row);
      return v1 === v2 ? null : v1;
    }
    return null;
  }

  // Handle CASE WHEN ... THEN ... ELSE ... END
  const caseMatch = trimmed.match(/^\s*CASE\s+(.+)\s+END\s*$/i);
  if (caseMatch) {
    return evaluateCase(caseMatch[1], row);
  }

  // Handle simple column reference
  if (/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(trimmed)) {
    return row[trimmed] ?? null;
  }

  // Handle binary operations: a + b, a - b, a * b, a / b, etc.
  const binOps = [
    { op: '||', fn: (a: any, b: any) => String(a ?? '') + String(b ?? '') },
    { op: 'AND', fn: (a: any, b: any) => (a && b) ? 1 : 0 },
    { op: 'OR', fn: (a: any, b: any) => (a || b) ? 1 : 0 },
    { op: '>=', fn: (a: any, b: any) => Number(a >= b) },
    { op: '<=', fn: (a: any, b: any) => Number(a <= b) },
    { op: '<>', fn: (a: any, b: any) => Number(a !== b) },
    { op: '!=', fn: (a: any, b: any) => Number(a !== b) },
    { op: '=', fn: (a: any, b: any) => Number(a === b) },
    { op: '+', fn: (a: any, b: any) => Number(a) + Number(b) },
    { op: '-', fn: (a: any, b: any) => Number(a) - Number(b) },
    { op: '*', fn: (a: any, b: any) => Number(a) * Number(b) },
    { op: '/', fn: (a: any, b: any) => Number(b) !== 0 ? Number(a) / Number(b) : null },
    { op: '%', fn: (a: any, b: any) => Number(a) % Number(b) },
  ];

  for (const { op, fn } of binOps) {
    const opRe = new RegExp(`^\\s*(.+?)\\s+${escapeRegex(op)}\\s+(.+?)\\s*$`, 'i');
    const binMatch = trimmed.match(opRe);
    if (binMatch) {
      const left = evaluateExpression(binMatch[1].trim(), row);
      const right = evaluateExpression(binMatch[3].trim(), row);
      return fn(left, right);
    }
  }

  // Handle function calls: UPPER(name), LOWER(name), LENGTH(name), etc.
  const funcMatch = trimmed.match(/^\s*([A-Z_]+)\s*\(\s*(.+)\s*\)\s*$/i);
  if (funcMatch) {
    const funcName = funcMatch[1].toUpperCase();
    const arg = evaluateExpression(funcMatch[2].trim(), row);

    switch (funcName) {
      case 'UPPER':
        return String(arg ?? '').toUpperCase();
      case 'LOWER':
        return String(arg ?? '').toLowerCase();
      case 'LENGTH':
        return String(arg ?? '').length;
      case 'ABS':
        return Math.abs(Number(arg));
      case 'TRIM':
        return String(arg ?? '').trim();
      case 'ROUND':
        return Math.round(Number(arg));
      case 'CEIL':
        return Math.ceil(Number(arg));
      case 'FLOOR':
        return Math.floor(Number(arg));
      case 'SQRT':
        return Math.sqrt(Number(arg));
      case 'POWER':
        return Math.pow(Number(arg), 2);
      default:
        logger.warn({ funcName }, 'Unsupported function in generated column expression');
        return null;
    }
  }

  // As a last resort, evaluate as a simple expression using math (safe subset only)
  try {
    const sanitized = trimmed.replace(/[^0-9+\-*/.()\s]/g, '');
    if (/^[\d+\-*/().\s]+$/.test(sanitized)) {
      return Function(`"use strict"; return (${sanitized})`)();
    }
  } catch {
    // Ignore evaluation errors
  }

  logger.warn({ expression: trimmed }, 'Unable to evaluate generated column expression');
  return null;
}

function evaluateCase(caseBody: string, row: Record<string, any>): any {
  const whenRe = /WHEN\s+(.+?)\s+THEN\s+(.+?)(?:\s+WHEN|\s+ELSE|\s+END)/gi;

  // Simple: walk through WHEN clauses
  const clauses: Array<{ condition: string; result: string }> = [];
  let lastIndex = 0;
  let whenMatch: RegExpExecArray | null;

  const caseForParse = caseBody;

  // Parse using iterative approach
  // We'll use a simple state machine
  const tokens = caseForParse.split(/\s+/);
  let i = 0;

  while (i < tokens.length) {
    if (tokens[i].toUpperCase() === 'WHEN') {
      i++;
      const conditionParts: string[] = [];
      while (i < tokens.length && tokens[i].toUpperCase() !== 'THEN') {
        conditionParts.push(tokens[i]);
        i++;
      }
      i++; // skip THEN
      const resultParts: string[] = [];
      while (
        i < tokens.length &&
        tokens[i].toUpperCase() !== 'WHEN' &&
        tokens[i].toUpperCase() !== 'ELSE' &&
        tokens[i].toUpperCase() !== 'END'
      ) {
        resultParts.push(tokens[i]);
        i++;
      }
      clauses.push({
        condition: conditionParts.join(' '),
        result: resultParts.join(' '),
      });
    } else if (tokens[i].toUpperCase() === 'ELSE') {
      i++;
      const elseParts: string[] = [];
      while (i < tokens.length && tokens[i].toUpperCase() !== 'END') {
        elseParts.push(tokens[i]);
        i++;
      }
      if (elseParts.length > 0) {
        clauses.push({ condition: 'true', result: elseParts.join(' ') });
      }
      i++; // skip END
    } else {
      i++;
    }
  }

  for (const clause of clauses) {
    try {
      const condVal = evaluateExpression(clause.condition, row);
      if (condVal) {
        return evaluateExpression(clause.result, row);
      }
    } catch {
      // Fall through to next clause
    }
  }

  return null;
}

function splitArgs(args: string): string[] {
  const result: string[] = [];
  let depth = 0;
  let current = '';
  for (let i = 0; i < args.length; i++) {
    const ch = args[i];
    if (ch === '(') { depth++; current += ch; }
    else if (ch === ')') { depth--; current += ch; }
    else if (ch === ',' && depth === 0) {
      result.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) result.push(current.trim());
  return result;
}

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
