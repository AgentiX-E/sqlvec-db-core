import { describe, it, expect } from 'vitest';
import {
  detectGeneratedColumn,
  rewriteGeneratedColumn,
  extractGeneratedDefs,
  resolveDependencies,
  computeGeneratedValues,
  GENERATED_IDENTITY_RE,
} from '../query/GeneratedColumnShim';

describe('detectGeneratedColumn', () => {
  it('detects GENERATED ALWAYS AS IDENTITY', () => {
    expect(detectGeneratedColumn('CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY)')).toBe(true);
  });
  it('detects GENERATED BY DEFAULT AS IDENTITY', () => {
    expect(detectGeneratedColumn('CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY)')).toBe(true);
  });
  it('detects GENERATED ALWAYS AS (expr) STORED', () => {
    expect(detectGeneratedColumn('CREATE TABLE t (x INT GENERATED ALWAYS AS (a+b) STORED)')).toBe(true);
  });
  it('does not detect inside a string literal', () => {
    expect(detectGeneratedColumn("CREATE TABLE t (x INT, n TEXT DEFAULT 'GENERATED ALWAYS AS')")).toBe(false);
  });
  it('does not detect inside a comment', () => {
    expect(detectGeneratedColumn('-- GENERATED ALWAYS AS\nCREATE TABLE t (x INT)')).toBe(false);
  });
  it('returns false for unrelated SQL', () => {
    expect(detectGeneratedColumn('SELECT 1')).toBe(false);
  });
  it('rejects null / undefined / blank', () => {
    expect(detectGeneratedColumn('')).toBe(false);
    expect(detectGeneratedColumn(null as unknown as string)).toBe(false);
    expect(detectGeneratedColumn(undefined as unknown as string)).toBe(false);
  });
});

describe('rewriteGeneratedColumn', () => {
  it('rewrites GENERATED ALWAYS AS IDENTITY', () => {
    const r = rewriteGeneratedColumn('CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY)');
    expect(r.rewritten).toBe(true);
    expect(r.sql).toBe('CREATE TABLE t (id INT )');
    expect(r.identityCols).toEqual([
      { table: 't', col: 'id', type: 'always', seqName: 't_id_seq' },
    ]);
  });
  it('rewrites GENERATED BY DEFAULT AS IDENTITY', () => {
    const r = rewriteGeneratedColumn('CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY)', 't');
    expect(r.rewritten).toBe(true);
    expect(r.identityCols).toEqual([
      { table: 't', col: 'id', type: 'default', seqName: 't_id_seq' },
    ]);
  });
  it('rewrites GENERATED ALWAYS AS (expr) STORED', () => {
    const r = rewriteGeneratedColumn('CREATE TABLE t (x INT GENERATED ALWAYS AS (a+b) STORED)');
    expect(r.rewritten).toBe(true);
    expect(r.sql).toBe('CREATE TABLE t (x INT AS (a+b) STORED)');
  });
  it('rewrites GENERATED ALWAYS AS (expr) without STORED', () => {
    const r = rewriteGeneratedColumn('CREATE TABLE t (x INT GENERATED ALWAYS AS (a+b))');
    expect(r.sql).toBe('CREATE TABLE t (x INT AS (a+b))');
  });
  it('does not rewrite a string literal containing the keyword', () => {
    const r = rewriteGeneratedColumn(
      "CREATE TABLE t (x INT, n TEXT DEFAULT 'GENERATED ALWAYS AS (x)')",
    );
    expect(r.rewritten).toBe(false);
    expect(r.sql).toBe("CREATE TABLE t (x INT, n TEXT DEFAULT 'GENERATED ALWAYS AS (x)')");
  });
  it('extracts table name from CREATE TABLE', () => {
    const r = rewriteGeneratedColumn('CREATE TABLE users (id INT GENERATED ALWAYS AS IDENTITY)');
    expect(r.identityCols?.[0]).toMatchObject({ table: 'users', col: 'id', seqName: 'users_id_seq' });
  });
  it('strips sequence options in IDENTITY', () => {
    const r = rewriteGeneratedColumn(
      'CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY (START WITH 100))',
    );
    expect(r.identityCols?.length).toBe(1);
    expect(r.sql).toBe('CREATE TABLE t (id INT )');
  });
  it('passes through null / blank', () => {
    expect(rewriteGeneratedColumn('')).toEqual({ sql: '', rewritten: false });
    expect(rewriteGeneratedColumn(null as unknown as string)).toEqual({ sql: '', rewritten: false });
  });
  it('uses provided tableName when SQL has no CREATE TABLE', () => {
    const r = rewriteGeneratedColumn('id INT GENERATED ALWAYS AS IDENTITY', 'my_table');
    expect(r.identityCols?.[0]).toMatchObject({ table: 'my_table', col: 'id', seqName: 'my_table_id_seq' });
  });
  it('does not extract a table name when no CREATE TABLE and no explicit name', () => {
    const r = rewriteGeneratedColumn('id INT GENERATED ALWAYS AS (a + b)');
    expect(r.rewritten).toBe(true);
    expect(r.identityCols).toBeUndefined();
  });
});

describe('extractGeneratedDefs', () => {
  it('extracts a simple generated column', () => {
    const defs = extractGeneratedDefs('CREATE TABLE t (a INT, b INT, c INT AS (a + b) STORED)');
    expect(defs).toEqual([
      { name: 'c', expression: 'a + b', stored: true, dependencies: ['a', 'b'] },
    ]);
  });
  it('extracts a nested function call without truncation', () => {
    const defs = extractGeneratedDefs('CREATE TABLE t (c INT AS (upper(name)) STORED)');
    expect(defs[0].expression).toBe('upper(name)');
    expect(defs[0].dependencies).toEqual(['name']);
  });
  it('returns [] for no generated columns', () => {
    expect(extractGeneratedDefs('CREATE TABLE t (a INT, b INT)')).toEqual([]);
  });
  it('skips a string literal containing AS()', () => {
    expect(extractGeneratedDefs("CREATE TABLE t (n TEXT DEFAULT 'AS (x) STORED')")).toEqual([]);
  });
  it('extracts an expression containing a literal with parens', () => {
    const defs = extractGeneratedDefs("CREATE TABLE t (c INT AS (a || 'x)y') STORED)");
    expect(defs[0].expression).toBe("a || 'x)y'");
  });
  it('stops on an unbalanced paren', () => {
    expect(extractGeneratedDefs('CREATE TABLE t (c INT AS (a + b')).toEqual([]);
  });
  it('rejects null / non-string', () => {
    expect(extractGeneratedDefs('')).toEqual([]);
    expect(extractGeneratedDefs(null as unknown as string)).toEqual([]);
  });
});

describe('resolveDependencies', () => {
  it('extracts simple column references', () => {
    expect(resolveDependencies('a + b', [])).toEqual(['a', 'b']);
  });
  it('extracts a nested function argument', () => {
    expect(resolveDependencies('upper(name)', [])).toEqual(['name']);
  });
  it('extracts CASE expression columns', () => {
    expect(resolveDependencies('CASE WHEN a > 0 THEN b ELSE c END', [])).toEqual(['a', 'b', 'c']);
  });
  it('ignores number literals', () => {
    expect(resolveDependencies('1 + 2', [])).toEqual([]);
  });
  it('dedupes repeated column references', () => {
    expect(resolveDependencies('a + a + b', [])).toEqual(['a', 'b']);
  });
  it('ignores SQL keywords', () => {
    expect(resolveDependencies('CASE WHEN x IS NULL THEN y END', [])).toEqual(['x', 'y']);
  });
  it('rejects null / empty', () => {
    expect(resolveDependencies('', [])).toEqual([]);
    expect(resolveDependencies(null as unknown as string, [])).toEqual([]);
  });
});

describe('computeGeneratedValues', () => {
  const one = (expr: string, row: Record<string, any>) =>
    computeGeneratedValues(row, Object.keys(row), [
      { name: 'c', expression: expr, stored: true, dependencies: [] },
    ]).c;

  it('computes a binary arithmetic expression', () => {
    expect(one('a + b', { a: 1, b: 2 })).toBe(3);
  });
  it('computes a CASE expression with comparison', () => {
    expect(one('CASE WHEN a > b THEN a ELSE b END', { a: 5, b: 3 })).toBe(5);
    expect(one('CASE WHEN a > b THEN a ELSE b END', { a: 3, b: 5 })).toBe(5);
  });
  it('computes a string concatenation', () => {
    expect(one('a || b', { a: 'x', b: 'y' })).toBe('xy');
  });
  it('handles NULL literal', () => {
    expect(one('NULL', {})).toBeNull();
  });
  it('handles boolean literals', () => {
    expect(one('TRUE', {})).toBe(1);
    expect(one('FALSE', {})).toBe(0);
  });
  it('handles numeric and string literals', () => {
    expect(one('42', {})).toBe(42);
    expect(one('3.14', {})).toBe(3.14);
    expect(one("'hello'", {})).toBe('hello');
  });
  it('handles COALESCE', () => {
    expect(one('COALESCE(a, 2)', { a: null })).toBe(2);
    expect(one('COALESCE(a, b)', { a: null, b: 7 })).toBe(7);
  });
  it('handles NULLIF', () => {
    expect(one('NULLIF(a, b)', { a: 0, b: 1 })).toBe(0);
    expect(one('NULLIF(a, b)', { a: 5, b: 5 })).toBeNull();
  });
  it('handles a simple column reference', () => {
    expect(one('a', { a: 5 })).toBe(5);
  });
  it('handles all comparison operators', () => {
    expect(one('a >= b', { a: 5, b: 5 })).toBe(1);
    expect(one('a <= b', { a: 5, b: 5 })).toBe(1);
    expect(one('a <> b', { a: 1, b: 2 })).toBe(1);
    expect(one('a != b', { a: 1, b: 2 })).toBe(1);
    expect(one('a < b', { a: 1, b: 2 })).toBe(1);
    expect(one('a = b', { a: 5, b: 5 })).toBe(1);
    expect(one('a = b', { a: 1, b: 2 })).toBe(0);
  });
  it('handles AND / OR', () => {
    expect(one('a AND b', { a: 1, b: 1 })).toBe(1);
    expect(one('a AND b', { a: 1, b: 0 })).toBe(0);
    expect(one('a OR b', { a: 0, b: 1 })).toBe(1);
    expect(one('a OR b', { a: 0, b: 0 })).toBe(0);
  });
  it('handles all arithmetic operators', () => {
    expect(one('a - b', { a: 10, b: 3 })).toBe(7);
    expect(one('a * b', { a: 3, b: 4 })).toBe(12);
    expect(one('a / b', { a: 10, b: 2 })).toBe(5);
    expect(one('a % b', { a: 10, b: 3 })).toBe(1);
  });
  it('returns null on division by zero', () => {
    expect(one('a / 0', { a: 5 })).toBeNull();
  });
  it('handles all scalar functions', () => {
    expect(one('UPPER(name)', { name: 'bob' })).toBe('BOB');
    expect(one('LOWER(name)', { name: 'BOB' })).toBe('bob');
    expect(one('LENGTH(name)', { name: 'abc' })).toBe(3);
    expect(one('ABS(a)', { a: -5 })).toBe(5);
    expect(one('TRIM(name)', { name: ' x ' })).toBe('x');
    expect(one('ROUND(a)', { a: 3.6 })).toBe(4);
    expect(one('CEIL(a)', { a: 3.2 })).toBe(4);
    expect(one('FLOOR(a)', { a: 3.8 })).toBe(3);
    expect(one('SQRT(a)', { a: 16 })).toBe(4);
    expect(one('POWER(a)', { a: 3 })).toBe(9);
  });
  it('returns null for an unsupported function', () => {
    expect(one('some_unknown(a)', { a: 5 })).toBeNull();
  });
  it('evaluates a pure numeric expression via fallback', () => {
    expect(one('1 + 2 * 3', {})).toBe(7);
  });
  it('evaluates a parenthesised expression correctly', () => {
    expect(one('2 * (3 + 4)', {})).toBe(14);
    expect(one('(a + b)', { a: 1, b: 2 })).toBe(3);
    expect(one('(a) + (b)', { a: 1, b: 2 })).toBe(3);
  });
  it('respects operator precedence', () => {
    expect(one('a + b * c', { a: 1, b: 2, c: 3 })).toBe(7);
    expect(one('a * b + c', { a: 1, b: 2, c: 3 })).toBe(5);
    expect(one('a - b - c', { a: 10, b: 3, c: 2 })).toBe(5);
  });
  it('does not confuse >= with >', () => {
    expect(one('a >= b', { a: 5, b: 5 })).toBe(1);
  });
  it('returns null for an uncomputable expression', () => {
    expect(one('a +', { a: 5 })).toBeNull();
  });
  it('returns null when a string function receives null', () => {
    expect(one('UPPER(a)', { a: null })).toBe('');
    expect(one('LOWER(a)', { a: null })).toBe('');
    expect(one('LENGTH(a)', { a: null })).toBe(0);
    expect(one('TRIM(a)', { a: null })).toBe('');
  });
  it('handles CASE with ELSE clause', () => {
    expect(one('CASE WHEN a > 0 THEN 1 ELSE 0 END', { a: 5 })).toBe(1);
    expect(one('CASE WHEN a > 0 THEN 1 ELSE 0 END', { a: -1 })).toBe(0);
  });
  it('handles CASE without ELSE (falls through to null)', () => {
    expect(one('CASE WHEN a > 0 THEN 1 END', { a: -1 })).toBeNull();
  });
  it('handles NULLIF with wrong arg count', () => {
    expect(one('NULLIF(a)', { a: 1 })).toBeNull();
  });
  it('handles a string concatenation with null operand', () => {
    expect(one('a || b', { a: null, b: 'x' })).toBe('x');
    expect(one('a || b', { a: 'x', b: null })).toBe('x');
  });
  it('handles a literal with an operator-like character inside', () => {
    expect(one("a || '+'", { a: 'x' })).toBe('x+');
  });
  it('handles nested parens in a function argument', () => {
    expect(one('COALESCE(a, b)', { a: null, b: 5 })).toBe(5);
    expect(one('COALESCE(f(a), b)', { a: null, b: 5 })).toBe(5);
  });
  it('handles a trailing empty COALESCE argument', () => {
    expect(one('COALESCE(a,)', { a: 1 })).toBe(1);
  });
  it('handles unknown function via switch default', () => {
    expect(one('ZEBRA(a)', { a: 1 })).toBeNull();
  });
});

describe('GENERATED_IDENTITY_RE', () => {
  it('matches GENERATED ALWAYS AS IDENTITY', () => {
    expect(GENERATED_IDENTITY_RE.test(' INT GENERATED ALWAYS AS IDENTITY')).toBe(true);
  });
  it('matches GENERATED BY DEFAULT AS IDENTITY', () => {
    expect(GENERATED_IDENTITY_RE.test(' INT GENERATED BY DEFAULT AS IDENTITY')).toBe(true);
  });
});
