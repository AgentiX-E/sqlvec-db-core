import { describe, it, expect } from 'vitest';
import {
  detectIdentityColumn,
  rewriteIdentityColumn,
  detectSerialColumn,
  rewriteSerialColumn,
} from '../query/IdentityColumnShim';

// IdentityColumnShim rewrites PostgreSQL GENERATED ... AS IDENTITY and SERIAL
// pseudo-types to SQLite INTEGER PRIMARY KEY AUTOINCREMENT, while preserving
// string literals (e.g. column DEFAULT values) and non-CREATE-TABLE input.
describe('IdentityColumnShim', () => {
  describe('rewriteIdentityColumn', () => {
    it('rewrites GENERATED ALWAYS AS IDENTITY', () => {
      expect(rewriteIdentityColumn('CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY)'))
        .toBe('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)');
    });

    it('rewrites GENERATED BY DEFAULT AS IDENTITY', () => {
      expect(rewriteIdentityColumn('CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY)'))
        .toBe('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)');
    });

    it('returns unchanged for non-CREATE-TABLE SQL', () => {
      expect(rewriteIdentityColumn('SELECT 1')).toBe('SELECT 1');
      expect(rewriteIdentityColumn('INSERT INTO t VALUES (1)')).toBe('INSERT INTO t VALUES (1)');
    });

    // BUG #75 regression: identity text inside a string default must survive.
    it('preserves identity text inside a string literal', () => {
      const sql = "CREATE TABLE t (c TEXT DEFAULT 'a INT GENERATED ALWAYS AS IDENTITY')";
      expect(rewriteIdentityColumn(sql)).toBe(sql);
    });
  });

  describe('detectIdentityColumn', () => {
    it('detects a real identity declaration', () => {
      expect(detectIdentityColumn('CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY)')).toBe(true);
    });

    it('detects BY DEFAULT variant', () => {
      expect(detectIdentityColumn('id BIGINT GENERATED BY DEFAULT AS IDENTITY')).toBe(true);
    });

    // BUG #73 regression: a mention inside a string is not a declaration.
    it('does not report a string literal mention', () => {
      expect(detectIdentityColumn("SELECT 'GENERATED ALWAYS AS IDENTITY'")).toBe(false);
    });
  });

  describe('rewriteSerialColumn', () => {
    it('rewrites the first SERIAL column to PRIMARY KEY AUTOINCREMENT', () => {
      expect(rewriteSerialColumn('CREATE TABLE t (id SERIAL)'))
        .toBe('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)');
    });

    it('rewrites subsequent SERIAL columns to plain INTEGER (single AUTOINCREMENT)', () => {
      expect(rewriteSerialColumn('CREATE TABLE t (id SERIAL, x BIGSERIAL)'))
        .toBe('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, x INTEGER)');
    });

    it('does not assign AUTOINCREMENT when a PRIMARY KEY already exists', () => {
      expect(rewriteSerialColumn('CREATE TABLE t (id SERIAL, x BIGSERIAL, PRIMARY KEY (x))'))
        .toBe('CREATE TABLE t (id INTEGER, x INTEGER, PRIMARY KEY (x))');
    });

    it('returns unchanged for non-CREATE-TABLE SQL', () => {
      expect(rewriteSerialColumn('SELECT 1')).toBe('SELECT 1');
    });

    it('handles SMALLSERIAL', () => {
      expect(rewriteSerialColumn('CREATE TABLE t (id SMALLSERIAL)'))
        .toBe('CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)');
    });

    // BUG #75 regression: a `DEFAULT 'x SERIAL y'` string must not be rewritten.
    it('preserves SERIAL text inside a string default value', () => {
      const sql = "CREATE TABLE t (c TEXT DEFAULT 'x SERIAL y')";
      expect(rewriteSerialColumn(sql)).toBe(sql);
    });
  });

  describe('detectSerialColumn', () => {
    it('detects a real SERIAL column', () => {
      expect(detectSerialColumn('CREATE TABLE t (id SERIAL)')).toBe(true);
    });

    it('detects BIGSERIAL/SMALLSERIAL', () => {
      expect(detectSerialColumn('CREATE TABLE t (id BIGSERIAL)')).toBe(true);
      expect(detectSerialColumn('CREATE TABLE t (id SMALLSERIAL)')).toBe(true);
    });

    it('returns false for non-CREATE-TABLE SQL', () => {
      expect(detectSerialColumn('SELECT SERIAL')).toBe(false);
    });

    // BUG #74 regression: a string default `'SERIAL'` is not a pseudo-type.
    it('does not report a SERIAL string default', () => {
      expect(detectSerialColumn("CREATE TABLE t (name TEXT DEFAULT 'SERIAL')")).toBe(false);
    });
  });
});
