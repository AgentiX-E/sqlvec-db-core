/**
 * End-to-end coverage for PostgreSQL identity columns and generated columns,
 * exercised through QueryRouter.execute() so the full rewrite path is reached:
 * DDL rewrite (GENERATED ... AS IDENTITY -> AUTOINCREMENT), INSERT identity
 * resolution (nextval / OVERRIDING SYSTEM VALUE / DEFAULT VALUES), and
 * generated-column expression evaluation.
 */
import { describe, it, expect, beforeAll } from 'vitest';
import Database from 'better-sqlite3';
import { QueryRouter } from '../query/QueryRouter';
import { VectorMetric, VectorMode, VectorIndexType } from '../types/types-raw';

let qr: QueryRouter;
let db: Database.Database;

beforeAll(() => {
  db = new Database(':memory:');
  const sm: any = {
    getAllShards: () => new Map([[0, { db, vectorIndex: null, readers: [] }] as any]),
    getShard: (n: number) => (n === 0 ? { db, vectorIndex: null, readers: [] } as any : undefined),
    execShard: async (_n: number, sql: string) => db.exec(sql),
    queryShard: (_n: number, sql: string, params?: any[]) => db.prepare(sql).all(...(params || [])),
    getShardCount: () => 1,
    getShardIdForKey: () => 0,
    getShardIds: () => [0],
    execAll: async (sql: string) => db.exec(sql),
    queryAll: async () => [],
    getStats: () => [],
    execAllBatch: async (sqls: string[]) => db.exec(sqls.join(';')),
    execBatchOnShard: async (_n: number, sqls: string[]) => db.exec(sqls.join(';')),
    rotateAllKeys: () => [{ success: true }],
  };
  const config: any = {
    enabled: true,
    dimension: 768,
    metric: VectorMetric.COSINE,
    mode: VectorMode.AUTO,
    bruteForceThreshold: 1000,
    indexType: VectorIndexType.FLAT,
    indexParams: {},
  };
  qr = new QueryRouter(sm, {} as any, config);
});

describe('identity columns (GENERATED AS IDENTITY)', () => {
  it('auto-assigns identity values on INSERT without the identity column', async () => {
    await qr.execute('CREATE TABLE users (id INT GENERATED ALWAYS AS IDENTITY, name TEXT)');
    await qr.execute("INSERT INTO users (name) VALUES ('alice')");
    await qr.execute("INSERT INTO users (name) VALUES ('bob')");
    const r = await qr.execute('SELECT id, name FROM users ORDER BY id');
    expect(r.rows).toEqual([
      { id: 1, name: 'alice' },
      { id: 2, name: 'bob' },
    ]);
  });

  it('supports GENERATED BY DEFAULT AS IDENTITY with explicit values', async () => {
    await qr.execute('CREATE TABLE items (id INT GENERATED BY DEFAULT AS IDENTITY, label TEXT)');
    await qr.execute("INSERT INTO items (label) VALUES ('auto')");
    await qr.execute("INSERT INTO items (id, label) VALUES (100, 'explicit')");
    const r = await qr.execute('SELECT id, label FROM items ORDER BY id');
    // BY DEFAULT allows both auto-assignment (id=1) and explicit values (id=100).
    expect(r.rows).toEqual([
      { id: 1, label: 'auto' },
      { id: 100, label: 'explicit' },
    ]);
  });

  it('expands INSERT ... DEFAULT VALUES with identity nextval', async () => {
    await qr.execute('CREATE TABLE seq0 (id INT GENERATED ALWAYS AS IDENTITY, note TEXT)');
    await qr.execute('INSERT INTO seq0 DEFAULT VALUES');
    const r = await qr.execute('SELECT id, note FROM seq0');
    expect(r.rows.length).toBe(1);
    expect(r.rows[0].id).toBe(1);
  });
});

describe('generated columns', () => {
  it('evaluates a generated column expression on INSERT', async () => {
    await qr.execute(
      'CREATE TABLE emp (base INT, doubled INT GENERATED ALWAYS AS (base * 2) STORED)',
    );
    await qr.execute('INSERT INTO emp (base) VALUES (21)');
    const r = await qr.execute('SELECT base, doubled FROM emp');
    expect(r.rows).toEqual([{ base: 21, doubled: 42 }]);
  });
});
